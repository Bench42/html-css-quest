export function voiceFor(msg) {
  let m;
  if ((m = /^Тег <(\w+)> не закрыт/.exec(msg))) return 'Дверь открыл, а закрыть забыл? Каждому <' + m[1] + '> нужен свой </' + m[1] + '>.';
  if (/^Лишний закрывающий/.test(msg)) return 'Закрываешь то, чего не открывал. Так не бывает.';
  if (/^Ожидался/.test(msg)) return 'Не в том порядке. Что открыл последним, закрой первым.';
  if ((m = /^Не нашёл тег <(\w+)>/.exec(msg))) return m[1] === 'h1' ? 'Где вывеска? Пустое место это не вывеска.' : 'А текст где? Под вывеской должен быть абзац.';
  if ((m = /^У тебя \d+ тегов <(\w+)>/.exec(msg))) return m[1] === 'h1' ? 'Вывеска одна. Две это уже балаган.' : 'Лишнее убери: нужен один.';
  if (/^В теге <\w+> должно быть/.test(msg)) return 'Буквы те, да не те. Сверь с образцом.';
  if (/^Абзац должен идти под/.test(msg)) return 'Вывеска над текстом, а не наоборот.';
  if (/^Слово «ночлег» должно быть жирным/.test(msg)) return 'Где нажим? Заверни «ночлег» в <b>, и слово станет жирным.';
  if (/^Жирным должно быть только/.test(msg)) return 'Жирным только «ночлег». Остальное не трогай.';
  if (/^Редактор пока пуст/.test(msg)) return 'Начни хоть с чего-нибудь. Тапни тег, и пара готова.';
  return '';
}
